export function countryNames() {
  return [...new Set(places.map((place) => place.country))]
}

export function citiesIn(country) {
  return places.filter((place) => place.country === country)
}

export function matchPlace({ country, city, timeZone } = {}) {
  const fromZone = String(timeZone || '').split('/').pop()?.replace(/_/g, ' ')
  return places.find((place) => place.country === country && place.city === city)
    || places.find((place) => place.timeZone === timeZone && place.city === city)
    || places.find((place) => place.timeZone === timeZone && place.city === fromZone)
    || places.find((place) => place.timeZone === timeZone)
    || null
}

