function pointOf(place) {
  const pair = place && coords[`${place.country}|${place.city}`]
  if (!pair) return null
  return { lat: pair[0], lng: pair[1], city: place.city }
}

function distanceKm(from, to) {
  const earth = 6371
  const toRad = (value) => (value * Math.PI) / 180
  const dLat = toRad(to.lat - from.lat)
  const dLng = toRad(to.lng - from.lng)
  const lat1 = toRad(from.lat)
  const lat2 = toRad(to.lat)
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(lat1) * Math.cos(lat2) * Math.sin(dLng / 2) ** 2
  return 2 * earth * Math.asin(Math.min(1, Math.sqrt(h)))
}

export function distanceBetween(fromPlace, toPlace) {
  const from = pointOf(fromPlace)
  const to = pointOf(toPlace)
  if (!from || !to) return null
  const km = distanceKm(from, to)
  const sameCity = from.city.localeCompare(to.city, undefined, { sensitivity: 'accent' }) === 0
  if (sameCity) {
    return { same: true, label: 'Same city', from: from.city, to: to.city }
  }
  const rounded = km >= 100 ? Math.round(km / 10) * 10 : Math.max(1, Math.round(km))
  return {
    same: false,
    km: rounded,
    label: `${rounded.toLocaleString('en-US')} km`,
    from: from.city,
    to: to.city,
  }
}
